package org.borue;

import java.io.FileInputStream;
import java.io.FileOutputStream;

import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import org.apache.poi.ss.usermodel.Cell;
import org.apache.poi.ss.usermodel.DataFormatter;
import org.apache.poi.ss.usermodel.Row;
import org.apache.poi.ss.usermodel.Sheet;

import org.apache.poi.xssf.usermodel.XSSFWorkbook;
//...............This is 5th step of statistical pipeline

/**
 * ============================================================
 * HolmCorrection
 * ============================================================
 *
 * INPUT:
 *
 * D:/BORUE/WilcoxonPairwiseResults.xlsx
 *
 *
 * OUTPUT:
 *
 * D:/BORUE/WilcoxonHolmCorrected.xlsx
 *
 *
 * PURPOSE
 * ------------------------------------------------------------
 *
 * Applies Holm's step-down multiple-comparison correction
 * to the raw p-values generated by:
 *
 *      WilcoxonPairwiseAnalyzer.java
 *
 *
 * CORRECTION FAMILIES
 * ------------------------------------------------------------
 *
 * Correction is performed SEPARATELY for:
 *
 *      Precision
 *      Recall
 *      F1
 *      Candidate Set Size
 *
 * Each family contains:
 *
 *      RASOM vs 9 baselines
 *
 * Therefore:
 *
 *      m = 9 hypotheses per family
 *
 *
 * HOLM PROCEDURE
 * ------------------------------------------------------------
 *
 * Raw p-values are sorted:
 *
 *      p(1) <= p(2) <= ... <= p(m)
 *
 * Preliminary adjusted values:
 *
 *      p_adj(i) = (m - i + 1) * p(i)
 *
 * Monotonicity is then enforced:
 *
 *      adjusted(i) =
 *          max(adjusted(i-1), p_adj(i))
 *
 * and values are capped at 1.0.
 *
 *
 * SIGNIFICANCE LEVEL
 * ------------------------------------------------------------
 *
 *      alpha = 0.05
 *
 * Significant if:
 *
 *      Holm-adjusted p <= 0.05
 *
 * ============================================================
 */
public class HolmCorrection {


    // ========================================================
    // FILE PATHS
    // ========================================================

    private static final String INPUT_FILE =
            "D:/BORUE/WilcoxonPairwiseResults.xlsx";


    private static final String OUTPUT_FILE =
            "D:/BORUE/WilcoxonHolmCorrected.xlsx";


    // ========================================================
    // CONFIGURATION
    // ========================================================

    private static final double ALPHA = 0.05;


    /*
     * Input columns from WilcoxonPairwiseResults.xlsx
     *
     * ZERO-BASED:
     *
     * A  ReferenceAlgorithm
     * B  BaselineAlgorithm
     * C  Metric
     * D  PairedConcepts
     * E  NonZeroPairs
     * F  ZeroDifferences
     * G  RomanMean
     * H  BaselineMean
     * I  MeanDifference
     * J  WPlus
     * K  WMinus
     * L  WStatistic
     * M  Z
     * N  RawPValue
     * O  RankBiserialCorrelation
     */

    private static final int METRIC_COLUMN = 2;       // C

    private static final int RAW_P_COLUMN = 13;       // N


    private static final DataFormatter DATA_FORMATTER =
            new DataFormatter();


    // ========================================================
    // MAIN
    // ========================================================

    public static void main(String[] args) {


        try {


            System.out.println();

            System.out.println(
                    "=============================================="
            );

            System.out.println(
                    "HOLM MULTIPLE-COMPARISON CORRECTION"
            );

            System.out.println(
                    "=============================================="
            );

            System.out.println();


            // ------------------------------------------------
            // Read Wilcoxon results.
            // ------------------------------------------------

            List<TestResult> tests =
                    readWilcoxonResults();


            System.out.println(
                    "Wilcoxon tests read: "
                    + tests.size()
            );


            if (tests.size() != 36) {


                System.out.println(
                        "WARNING: Expected 36 Wilcoxon tests."
                );

            }


            // ------------------------------------------------
            // Group by metric family.
            // ------------------------------------------------

            Map<String, List<TestResult>> families =
                    groupByMetric(
                            tests
                    );


            System.out.println();

            System.out.println(
                    "Metric families found: "
                    + families.size()
            );


            // ------------------------------------------------
            // Apply Holm correction separately to each family.
            // ------------------------------------------------

            for (Map.Entry<String, List<TestResult>> entry
                    : families.entrySet()) {


                String metric =
                        entry.getKey();


                List<TestResult> family =
                        entry.getValue();


                System.out.println();

                System.out.println(
                        "----------------------------------------------"
                );

                System.out.println(
                        "Metric family: "
                        + metric
                );


                System.out.println(
                        "Comparisons: "
                        + family.size()
                );


                if (family.size() != 9) {


                    System.out.println(
                            "WARNING: Expected 9 comparisons "
                            + "for this metric family."
                    );

                }


                applyHolmCorrection(
                        family
                );


                printFamily(
                        family
                );

            }


            // ------------------------------------------------
            // Write corrected workbook.
            // ------------------------------------------------

            writeOutput(
                    tests
            );


            System.out.println();

            System.out.println(
                    "=============================================="
            );

            System.out.println(
                    "HOLM CORRECTION COMPLETED SUCCESSFULLY"
            );

            System.out.println(
                    "=============================================="
            );

            System.out.println();

            System.out.println(
                    "Output file:"
            );

            System.out.println(
                    OUTPUT_FILE
            );


            System.out.println();

            System.out.println(
                    "Expected output:"
            );

            System.out.println(
                    "36 data rows + 1 heading = 37 rows"
            );


        }
        catch (Exception e) {


            e.printStackTrace();

        }

    }


    // ========================================================
    // READ WILCOXON RESULTS
    // ========================================================

    private static List<TestResult>
            readWilcoxonResults()
            throws Exception {


        FileInputStream input =
                new FileInputStream(
                        INPUT_FILE
                );


        XSSFWorkbook workbook =
                new XSSFWorkbook(
                        input
                );


        Sheet sheet =
                workbook.getSheetAt(0);


        List<TestResult> tests =
                new ArrayList<TestResult>();


        // ----------------------------------------------------
        // Row 0 = heading.
        // ----------------------------------------------------

        for (int rowNumber = 1;
             rowNumber <= sheet.getLastRowNum();
             rowNumber++) {


            Row row =
                    sheet.getRow(
                            rowNumber
                    );


            if (row == null) {

                continue;

            }


            String metric =
                    getString(
                            row,
                            METRIC_COLUMN
                    );


            if (metric.isEmpty()) {

                continue;

            }


            TestResult result =
                    new TestResult();


            /*
             * Preserve all 15 original columns as strings.
             * When writing the output, numeric columns will
             * be restored as numeric values where appropriate.
             */

            result.referenceAlgorithm =
                    getString(row, 0);


            result.baselineAlgorithm =
                    getString(row, 1);


            result.metric =
                    metric;


            result.pairedConcepts =
                    getDouble(row, 3);


            result.nonZeroPairs =
                    getDouble(row, 4);


            result.zeroDifferences =
                    getDouble(row, 5);


            result.romanMean =
                    getDouble(row, 6);


            result.baselineMean =
                    getDouble(row, 7);


            result.meanDifference =
                    getDouble(row, 8);


            result.wPlus =
                    getDouble(row, 9);


            result.wMinus =
                    getDouble(row, 10);


            result.wStatistic =
                    getDouble(row, 11);


            result.z =
                    getDouble(row, 12);


            result.rawPValue =
                    getDouble(
                            row,
                            RAW_P_COLUMN
                    );


            result.rankBiserialCorrelation =
                    getDouble(row, 14);


            /*
             * Keep original row number so corrected results
             * can later be written in the same order as the
             * Wilcoxon workbook.
             */

            result.originalOrder =
                    tests.size();


            tests.add(
                    result
            );

        }


        workbook.close();

        input.close();


        return tests;

    }


    // ========================================================
    // GROUP TESTS BY METRIC
    // ========================================================

    private static Map<String, List<TestResult>>
            groupByMetric(
                    List<TestResult> tests) {


        Map<String, List<TestResult>> families =
                new LinkedHashMap<String, List<TestResult>>();


        for (TestResult test : tests) {


            List<TestResult> family =
                    families.get(
                            test.metric
                    );


            if (family == null) {


                family =
                        new ArrayList<TestResult>();


                families.put(
                        test.metric,
                        family
                );

            }


            family.add(
                    test
            );

        }


        return families;

    }


    // ========================================================
    // APPLY HOLM CORRECTION
    // ========================================================

    private static void applyHolmCorrection(
            List<TestResult> family) {


        /*
         * Work on a copy because we want to preserve the
         * original Excel ordering.
         */

        List<TestResult> sorted =
                new ArrayList<TestResult>(
                        family
                );


        // ----------------------------------------------------
        // Sort from smallest raw p-value to largest.
        // ----------------------------------------------------

        Collections.sort(
                sorted,
                new Comparator<TestResult>() {

                    @Override
                    public int compare(
                            TestResult a,
                            TestResult b) {


                        return Double.compare(
                                a.rawPValue,
                                b.rawPValue
                        );

                    }

                }
        );


        int m =
                sorted.size();


        double previousAdjusted =
                0.0;


        // ----------------------------------------------------
        // Holm adjusted p-values.
        // ----------------------------------------------------

        for (int i = 0;
             i < m;
             i++) {


            TestResult test =
                    sorted.get(i);


            /*
             * i is zero-based.
             *
             * For m = 9:
             *
             * smallest p multiplied by 9
             * second smallest multiplied by 8
             * ...
             * largest multiplied by 1
             */

            int multiplier =
                    m - i;


            double preliminaryAdjusted =
                    test.rawPValue
                    *
                    multiplier;


            // ------------------------------------------------
            // Cap at 1.
            // ------------------------------------------------

            if (preliminaryAdjusted > 1.0) {


                preliminaryAdjusted =
                        1.0;

            }


            // ------------------------------------------------
            // Enforce monotonicity.
            // ------------------------------------------------

            double adjusted =
                    Math.max(
                            previousAdjusted,
                            preliminaryAdjusted
                    );


            if (adjusted > 1.0) {


                adjusted =
                        1.0;

            }


            test.holmAdjustedPValue =
                    adjusted;


            test.significant =
                    adjusted <= ALPHA;


            /*
             * Store Holm rank for auditability.
             *
             * Rank 1 = smallest raw p-value.
             */

            test.holmRank =
                    i + 1;


            test.holmMultiplier =
                    multiplier;


            previousAdjusted =
                    adjusted;

        }

    }


    // ========================================================
    // PRINT FAMILY
    // ========================================================

    private static void printFamily(
            List<TestResult> family) {


        /*
         * Sort temporary copy by Holm rank for readable
         * console output.
         */

        List<TestResult> sorted =
                new ArrayList<TestResult>(
                        family
                );


        Collections.sort(
                sorted,
                new Comparator<TestResult>() {

                    @Override
                    public int compare(
                            TestResult a,
                            TestResult b) {


                        return Integer.compare(
                                a.holmRank,
                                b.holmRank
                        );

                    }

                }
        );


        for (TestResult test : sorted) {


            System.out.println();


            System.out.println(
                    "Baseline: "
                    + test.baselineAlgorithm
            );


            System.out.println(
                    "Raw p-value: "
                    + test.rawPValue
            );


            System.out.println(
                    "Holm rank: "
                    + test.holmRank
            );


            System.out.println(
                    "Holm multiplier: "
                    + test.holmMultiplier
            );


            System.out.println(
                    "Holm-adjusted p-value: "
                    + test.holmAdjustedPValue
            );


            System.out.println(
                    "Significant at alpha = 0.05: "
                    + test.significant
            );

        }

    }


    // ========================================================
    // WRITE OUTPUT
    // ========================================================

    private static void writeOutput(
            List<TestResult> tests)
            throws Exception {


        /*
         * Restore original Wilcoxon row ordering.
         */

        Collections.sort(
                tests,
                new Comparator<TestResult>() {

                    @Override
                    public int compare(
                            TestResult a,
                            TestResult b) {


                        return Integer.compare(
                                a.originalOrder,
                                b.originalOrder
                        );

                    }

                }
        );


        XSSFWorkbook workbook =
                new XSSFWorkbook();


        Sheet sheet =
                workbook.createSheet(
                        "Wilcoxon Holm Corrected"
                );


        createHeader(
                sheet
        );


        int rowNumber = 1;


        for (TestResult result : tests) {


            Row row =
                    sheet.createRow(
                            rowNumber
                    );


            // ------------------------------------------------
            // Original Wilcoxon columns A-O
            // ------------------------------------------------

            row.createCell(0)
               .setCellValue(
                       result.referenceAlgorithm
               );


            row.createCell(1)
               .setCellValue(
                       result.baselineAlgorithm
               );


            row.createCell(2)
               .setCellValue(
                       result.metric
               );


            row.createCell(3)
               .setCellValue(
                       result.pairedConcepts
               );


            row.createCell(4)
               .setCellValue(
                       result.nonZeroPairs
               );


            row.createCell(5)
               .setCellValue(
                       result.zeroDifferences
               );


            row.createCell(6)
               .setCellValue(
                       result.romanMean
               );


            row.createCell(7)
               .setCellValue(
                       result.baselineMean
               );


            row.createCell(8)
               .setCellValue(
                       result.meanDifference
               );


            row.createCell(9)
               .setCellValue(
                       result.wPlus
               );


            row.createCell(10)
               .setCellValue(
                       result.wMinus
               );


            row.createCell(11)
               .setCellValue(
                       result.wStatistic
               );


            row.createCell(12)
               .setCellValue(
                       result.z
               );


            row.createCell(13)
               .setCellValue(
                       result.rawPValue
               );


            row.createCell(14)
               .setCellValue(
                       result.rankBiserialCorrelation
               );


            // ------------------------------------------------
            // New Holm columns P-S
            // ------------------------------------------------

            row.createCell(15)
               .setCellValue(
                       result.holmRank
               );


            row.createCell(16)
               .setCellValue(
                       result.holmMultiplier
               );


            row.createCell(17)
               .setCellValue(
                       result.holmAdjustedPValue
               );


            row.createCell(18)
               .setCellValue(
                       result.significant
               );


            rowNumber++;

        }


        // ----------------------------------------------------
        // Freeze header.
        // ----------------------------------------------------

        sheet.createFreezePane(
                0,
                1
        );


        // ----------------------------------------------------
        // Auto-size all 19 columns.
        // ----------------------------------------------------

        for (int column = 0;
             column < 19;
             column++) {


            sheet.autoSizeColumn(
                    column
            );

        }


        // ----------------------------------------------------
        // Save.
        // ----------------------------------------------------

        FileOutputStream output =
                new FileOutputStream(
                        OUTPUT_FILE
                );


        workbook.write(
                output
        );


        output.close();

        workbook.close();

    }


    // ========================================================
    // CREATE HEADER
    // ========================================================

    private static void createHeader(
            Sheet sheet) {


        Row row =
                sheet.createRow(0);


        String[] headings = {

                "ReferenceAlgorithm",
                "BaselineAlgorithm",
                "Metric",
                "PairedConcepts",
                "NonZeroPairs",
                "ZeroDifferences",
                "RomanMean",
                "BaselineMean",
                "MeanDifference",
                "WPlus",
                "WMinus",
                "WStatistic",
                "Z",
                "RawPValue",
                "RankBiserialCorrelation",

                // Holm columns

                "HolmRank",
                "HolmMultiplier",
                "HolmAdjustedPValue",
                "SignificantAt0.05"

        };


        for (int i = 0;
             i < headings.length;
             i++) {


            row.createCell(i)
               .setCellValue(
                       headings[i]
               );

        }

    }


    // ========================================================
    // GET STRING CELL
    // ========================================================

    private static String getString(
            Row row,
            int column) {


        Cell cell =
                row.getCell(
                        column
                );


        if (cell == null) {

            return "";

        }


        return DATA_FORMATTER
                .formatCellValue(
                        cell
                )
                .trim();

    }


    // ========================================================
    // GET NUMERIC CELL
    //
    // Compatible with your older Apache POI version.
    // ========================================================

    private static double getDouble(
            Row row,
            int column) {


        Cell cell =
                row.getCell(
                        column
                );


        if (cell == null) {

            return 0.0;

        }


        if (cell.getCellType()
                == Cell.CELL_TYPE_NUMERIC) {


            return cell.getNumericCellValue();

        }


        String value =
                DATA_FORMATTER
                .formatCellValue(
                        cell
                )
                .trim();


        if (value.isEmpty()) {

            return 0.0;

        }


        try {


            return Double.parseDouble(
                    value
            );

        }
        catch (NumberFormatException e) {


            throw new IllegalArgumentException(
                    "Invalid numeric value: "
                    + value
                    + " | Excel row: "
                    + (row.getRowNum() + 1)
                    + " | Column: "
                    + (column + 1)
            );

        }

    }


    // ========================================================
    // RESULT CONTAINER
    // ========================================================

    private static class TestResult {


        String referenceAlgorithm;

        String baselineAlgorithm;

        String metric;


        double pairedConcepts;

        double nonZeroPairs;

        double zeroDifferences;


        double romanMean;

        double baselineMean;

        double meanDifference;


        double wPlus;

        double wMinus;

        double wStatistic;


        double z;

        double rawPValue;

        double rankBiserialCorrelation;


        // ----------------------------------------------------
        // Holm results
        // ----------------------------------------------------

        int holmRank;

        int holmMultiplier;

        double holmAdjustedPValue;

        boolean significant;


        int originalOrder;

    }

}
